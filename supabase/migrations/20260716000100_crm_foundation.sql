-- CRM foundation: additive schema for the professional CRM roadmap.
-- This migration does not modify or delete public.empresas_formales.
-- Apply first in staging and only after supabase_security_hardening.sql.

begin;

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

-- The production project already has this table. Keeping the minimal definition
-- here makes the migration self-contained for fresh local/staging databases.
create table if not exists public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  updated_at timestamptz,
  full_name text,
  role text default 'asesor'
);

create table if not exists public.user_zones (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null,
  municipality text not null,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

create or replace function private.crm_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role in ('admin', 'superAdmin')
  );
$$;

create or replace function private.crm_set_updated_at()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.updated_at = timezone('utc'::text, now());
  return new;
end;
$$;

revoke all on function private.crm_is_admin() from public, anon;
grant execute on function private.crm_is_admin() to authenticated;
revoke all on function private.crm_set_updated_at() from public, anon, authenticated;

