  constraint crm_accounts_source_allowed check (source in ('manual', 'google_places', 'import', 'database', 'referral', 'campaign')),
  constraint crm_accounts_priority_allowed check (priority in ('low', 'medium', 'high', 'urgent')),
  constraint crm_accounts_enrichment_allowed check (enrichment_status in ('pending', 'processing', 'enriched', 'retrying', 'failed', 'skipped')),
  constraint crm_accounts_confidence_range check (data_confidence is null or data_confidence between 0 and 100)
