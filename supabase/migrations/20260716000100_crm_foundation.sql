create or replace function private.crm_can_access_account(target_account_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.crm_accounts account
    where account.id = target_account_id
      and (
        (select private.crm_is_admin())
        or account.owner_id = (select auth.uid())
        or account.created_by = (select auth.uid())
        or (
          account.owner_id is null
          and upper(coalesce(account.municipality, '')) in (
            select upper(zone.municipality)
            from public.user_zones zone
            where zone.user_id = (select auth.uid())
          )
        )
      )
  );
$$;

create or replace function private.crm_can_access_run(target_run_id uuid)
returns boolean
