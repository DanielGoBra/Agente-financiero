-- =========================================================================
-- 1. Tabla de Perfiles de Usuario (Profiles)
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  updated_at TIMESTAMP WITH TIME ZONE,
  full_name TEXT,
  role TEXT DEFAULT 'asesor'
);

-- Habilitar RLS en profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Políticas de RLS para profiles
CREATE POLICY "Permitir lectura del propio perfil" ON public.profiles
  FOR SELECT USING (auth.uid() = id);

CREATE POLICY "Permitir actualización del propio perfil" ON public.profiles
  FOR UPDATE USING (auth.uid() = id);

-- Trigger para crear un perfil automático cuando se registra un usuario en auth.users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, role)
  VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'full_name', new.email),
    'asesor'
  );
  
  -- Por defecto, le asignamos Envigado como su zona inicial de prueba
  INSERT INTO public.user_zones (user_id, municipality)
  VALUES (new.id, 'Envigado');
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- =========================================================================
-- 2. Tabla de Zonas Asignadas a Usuarios (User Zones)
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.user_zones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  municipality TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Habilitar RLS en user_zones
ALTER TABLE public.user_zones ENABLE ROW LEVEL SECURITY;

-- Políticas de RLS para user_zones
CREATE POLICY "Permitir lectura de zonas propias" ON public.user_zones
  FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Permitir inserción de zonas propias (admin/auto)" ON public.user_zones
  FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Permitir eliminación de zonas propias" ON public.user_zones
  FOR DELETE USING (auth.uid() = user_id);


-- =========================================================================
-- 3. Tabla de Leads del CRM (CRM Leads)
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.crm_leads (
  id TEXT PRIMARY KEY, -- Coincide con el id generado por el frontend (ej: place_id)
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  name TEXT NOT NULL,
  address TEXT NOT NULL,
  phone TEXT,
  website TEXT,
  municipality TEXT NOT NULL,
  estimated_size TEXT NOT NULL,
  reliability_score INTEGER NOT NULL,
  opportunity_score INTEGER NOT NULL,
  predicted_need TEXT NOT NULL,
  reasoning TEXT,
  status TEXT DEFAULT 'nuevo' NOT NULL,
  notes TEXT DEFAULT '' NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Habilitar RLS en crm_leads
ALTER TABLE public.crm_leads ENABLE ROW LEVEL SECURITY;

-- Políticas de RLS para crm_leads
CREATE POLICY "Permitir lectura de leads propios" ON public.crm_leads
  FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Permitir inserción de leads propios" ON public.crm_leads
  FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Permitir actualización de leads propios" ON public.crm_leads
  FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Permitir eliminación de leads propios" ON public.crm_leads
  FOR DELETE USING (auth.uid() = user_id);
